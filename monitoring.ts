import * as pulumi from "@pulumi/pulumi";
import * as k8s from "@pulumi/kubernetes";
import * as random from "@pulumi/random";

/**
 * Monitoring stack for the Guestbook application.
 *
 * Components:
 *   - Prometheus Operator
 *   - Prometheus
 *   - Grafana
 *   - kube-state-metrics
 *   - node-exporter
 *
 * The stack is installed using the prometheus-community
 * kube-prometheus-stack Helm chart.
 */

// -----------------------------------------------------------------------------
// Configuration
// -----------------------------------------------------------------------------

const grafanaPort = 30300;

const monitoringLabels = {
    "app.kubernetes.io/part-of": "guestbook-monitoring",
};

// -----------------------------------------------------------------------------
// Namespace
// -----------------------------------------------------------------------------

export const monitoringNamespace =
    new k8s.core.v1.Namespace("monitoring-namespace", {
        metadata: {
            name: "monitoring",
            labels: monitoringLabels,
        },
    });

// -----------------------------------------------------------------------------
// Grafana administrator password
//
// Generated by Pulumi instead of storing a password in Git.
// -----------------------------------------------------------------------------

const grafanaPassword =
    new random.RandomPassword("grafana-admin-password", {
        length: 20,
        special: true,
        overrideSpecial: "_%@-",
    });

// -----------------------------------------------------------------------------
// kube-prometheus-stack
// -----------------------------------------------------------------------------

export const monitoringStack =
    new k8s.helm.v3.Release(
        "kube-prometheus-stack",
        {
            name: "monitoring",
            chart: "kube-prometheus-stack",

            // Pinning the chart makes deployments reproducible.
            version: "92.14.1",

            namespace: monitoringNamespace.metadata.name,

            repositoryOpts: {
                repo:
                    "https://prometheus-community.github.io/helm-charts",
            },

            values: {
                // -------------------------------------------------------------
                // Grafana
                // -------------------------------------------------------------

                grafana: {
                    enabled: true,

                    adminUser: "admin",

                    adminPassword:
                        grafanaPassword.result,

                    service: {
                        type: "NodePort",
                        nodePort: grafanaPort,
                    },

                    defaultDashboardsEnabled: true,
                },

                // -------------------------------------------------------------
                // Prometheus
                // -------------------------------------------------------------

                prometheus: {
                    prometheusSpec: {
                        /**
                         * Allow Prometheus to discover ServiceMonitor resources
                         * created outside the Helm release and outside the
                         * monitoring namespace.
                         *
                         * This is required because our Guestbook resources
                         * live in the "guestbook" namespace.
                         */
                        serviceMonitorSelectorNilUsesHelmValues:
                            false,

                        serviceMonitorSelector: {},

                        serviceMonitorNamespaceSelector:
                            {},

                        podMonitorSelectorNilUsesHelmValues:
                            false,

                        podMonitorSelector: {},

                        podMonitorNamespaceSelector:
                            {},

                        retention: "2d",
                    },
                },

                // -------------------------------------------------------------
                // Alertmanager
                //
                // Alertmanager is not required by the coding assignment.
                // Disabling it reduces resource consumption on a local cluster.
                // -------------------------------------------------------------

                alertmanager: {
                    enabled: false,
                },

                // -------------------------------------------------------------
                // Kubernetes metrics
                // -------------------------------------------------------------

                kubeStateMetrics: {
                    enabled: true,
                },

                nodeExporter: {
                    enabled: true,
                },
            },

            skipAwait: false,

            timeout: 600,
        },
        {
            dependsOn: [
                monitoringNamespace,
            ],
        },
    );

// -----------------------------------------------------------------------------
// Stack outputs
// -----------------------------------------------------------------------------

export const monitoringNamespaceName =
    monitoringNamespace.metadata.name;

export const grafanaAdminUser =
    "admin";

export const grafanaAdminPassword =
    pulumi.secret(grafanaPassword.result);

export const grafanaNodePort =
    grafanaPort;

/**
 * Docker Desktop exposes NodePort services through localhost.
 *
 * For another Kubernetes environment, use:
 *
 *   http://<node-ip>:30300
 */
export const grafanaUrl =
    pulumi.output(
        `http://localhost:${grafanaPort}`,
    );

export const prometheusReleaseName =
    "monitoring";